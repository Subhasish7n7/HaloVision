"""
HaloVision YOLO dataset generator: writes halovision_v2.yaml (D: + repo mirror).

The dataset YAML lives with the data on D: and a mirror copy stays in the repo
for reference. `path` is absolute (D:) so ultralytics resolves it regardless of CWD.

Usage:
    python ml/training/generate_yaml.py
"""

import json
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hv_paths import DATASET_YAML, REPO_DATASET_YAML_MIRROR  # noqa: E402

# FROZEN class mapping — SINGLE SOURCE OF TRUTH is class_mapping.json
# (80 COCO 0-79 + 15 HaloVision 80-94; frozen IDs per the HaloVision V2 spec).
_CLASS_MAPPING = Path(__file__).resolve().parent / "class_mapping.json"
NAMES = {
    int(k): v
    for k, v in json.loads(_CLASS_MAPPING.read_text(encoding="utf-8"))["classes"].items()
}

assert len(NAMES) == 95 and max(NAMES) == 94


def build_cfg(path_str: str) -> dict:
    return {
        "path": path_str,
        "train": "images/train",
        "val": "images/val",
        "test": "images/test",
        "nc": 95,
        "names": NAMES,
    }


def main():
    # D: copy: absolute path (what training actually uses)
    d_cfg = build_cfg(str(DATASET_YAML.parent).replace("\\", "/"))
    DATASET_YAML.parent.mkdir(parents=True, exist_ok=True)
    DATASET_YAML.write_text(
        "# Generated by ml/training/generate_yaml.py - 95 classes (COCO 0-79 + HaloVision 80-94)\n"
        + yaml.safe_dump(d_cfg, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    print(f"wrote {DATASET_YAML}")

    # Repo mirror: relative path note + same names (reference copy)
    REPO_DATASET_YAML_MIRROR.parent.mkdir(parents=True, exist_ok=True)
    REPO_DATASET_YAML_MIRROR.write_text(
        "# REFERENCE MIRROR - authoritative copy lives on D: (HALOVISION_DATA_DIR)\n"
        f"# path: {d_cfg['path']}\n"
        + yaml.safe_dump(d_cfg, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    print(f"wrote {REPO_DATASET_YAML_MIRROR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
