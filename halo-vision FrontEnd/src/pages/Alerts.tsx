import { useState, useEffect } from "react";
import "./alerts.css";

type Alert = {
  id: number;
  type: string;
  severity: number;
  message: string;
  object_label: string | null;
  timestamp: string;
};

export default function Alerts() {
  const [alerts, setAlerts] = useState<Alert[]>([]);

  useEffect(() => {
    const token = localStorage.getItem("token");
    fetch("http://localhost:8000/api/alerts", {
      headers: { Authorization: `Bearer ${token}` },
    })
      .then((res) => res.json())
      .then((data) => setAlerts(data))
      .catch(() => {});
  }, []);

  const getSeverityColor = (s: number) => {
    if (s >= 4) return "red";
    if (s >= 3) return "orange";
    if (s >= 2) return "yellow";
    return "cyan";
  };

  const severityLabel = (s: number) => {
    if (s >= 4) return "CRITICAL";
    if (s >= 3) return "HIGH";
    if (s >= 2) return "MEDIUM";
    return "LOW";
  };

  return (
    <div className="alerts-container">
      <div className="alerts-header">
        <h2>Alert History</h2>
        <p>Security and threat alerts generated by the system</p>
      </div>

      {alerts.length === 0 ? (
        <p className="alerts-empty">No alerts recorded</p>
      ) : (
        <div className="alerts-list">
          {alerts.map((a) => (
            <div key={a.id} className="alert-card">
              <div className="alert-card-top">
                <span
                  className="alert-badge"
                  style={{
                    borderColor: getSeverityColor(a.severity),
                    color: getSeverityColor(a.severity),
                  }}
                >
                  {severityLabel(a.severity)}
                </span>
                <span className="alert-type">{a.type}</span>
                <span className="alert-time">
                  {new Date(a.timestamp).toLocaleString()}
                </span>
              </div>
              <p className="alert-message">{a.message}</p>
              {a.object_label && (
                <span className="alert-object">Object: {a.object_label}</span>
              )}
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
